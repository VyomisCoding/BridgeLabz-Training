public class averagePercentMarks {
    public static void main(String[] args) {
        int mathsMarks = 94;
        int physicsMarks = 95;
        int chemMarks = 96;
        int totalMarks = mathsMarks + physicsMarks + chemMarks;
        double averagePercent = (totalMarks / 3.0);
        System.out.println("Average Percentage Marks: " + averagePercent + "%");
    }
}
